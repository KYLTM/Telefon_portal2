-- ========================================================
-- Database Schema for KYLTM Employee Portal
-- PostgreSQL Dialect (Synchronized with portal_backup2.sql)
-- ========================================================

-- Drop existing tables in reverse dependency order to ensure clean initialization
DROP TABLE IF EXISTS meetings CASCADE;
DROP TABLE IF EXISTS employee_edit_requests CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS sectors CASCADE;
DROP TABLE IF EXISTS positions CASCADE;
DROP TABLE IF EXISTS departments CASCADE;
DROP TABLE IF EXISTS portal_users CASCADE;

-- 1. Departments Domain Table (Şöbələr)
CREATE TABLE departments (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT departments_pkey PRIMARY KEY (id),
    CONSTRAINT departments_name_key UNIQUE (name)
);

-- 2. Positions Domain Table (Vəzifələr)
CREATE TABLE positions (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT positions_pkey PRIMARY KEY (id),
    CONSTRAINT positions_name_key UNIQUE (name)
);

-- 3. Sectors Domain Table (Sektorlar — Şöbəyə bağlıdır)
CREATE TABLE sectors (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    dept_id bigint NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT sectors_pkey PRIMARY KEY (id),
    CONSTRAINT sectors_name_dept_unique UNIQUE (name, dept_id),
    CONSTRAINT sectors_dept_id_fkey FOREIGN KEY (dept_id) REFERENCES departments(id) ON DELETE CASCADE
);

-- 4. Portal Users Table (Admin və İclas İdarəçiləri)
CREATE TABLE portal_users (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    username text NOT NULL,
    email text,
    role text NOT NULL DEFAULT 'user'::text,
    password text NOT NULL,
    dept_id bigint REFERENCES departments(id) ON DELETE SET NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT portal_users_pkey PRIMARY KEY (id),
    CONSTRAINT portal_users_username_key UNIQUE (username)
);

-- 5. Employees Table (Əməkdaşlar)
CREATE TABLE employees (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    position_id bigint,
    dept_id bigint,
    sector_id bigint,
    email text,
    intphone text,
    mobile text,
    room text,
    car_plate text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    CONSTRAINT employees_pkey PRIMARY KEY (id),
    CONSTRAINT employees_dept_id_fkey FOREIGN KEY (dept_id) REFERENCES departments(id) ON DELETE SET NULL,
    CONSTRAINT employees_position_id_fkey FOREIGN KEY (position_id) REFERENCES positions(id) ON DELETE SET NULL,
    CONSTRAINT employees_sector_id_fkey FOREIGN KEY (sector_id) REFERENCES sectors(id) ON DELETE SET NULL
);

-- 6. Employee Edit Requests Table (Redaktə, Yeni Əməkdaş və Silmə Sorğuları)
CREATE TABLE employee_edit_requests (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    employee_id integer,
    employee_name text,
    old_data jsonb,
    new_data jsonb,
    status text DEFAULT 'pending'::text,
    requested_by text,
    request_type text DEFAULT 'edit'::text,
    requested_at timestamp with time zone DEFAULT now(),
    resolved_at timestamp with time zone,
    CONSTRAINT employee_edit_requests_pkey PRIMARY KEY (id)
);

-- 7. Meetings Table (İclas Otağı / Rezervasiyalar)
CREATE TABLE meetings (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title text NOT NULL,
    organizer text NOT NULL,
    meeting_date date NOT NULL,
    start_time time without time zone NOT NULL,
    end_time time without time zone NOT NULL,
    description text,
    participants jsonb DEFAULT '[]'::jsonb,
    reminder_sent boolean DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    CONSTRAINT meetings_pkey PRIMARY KEY (id)
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_sectors_dept_id ON sectors (dept_id);
CREATE INDEX IF NOT EXISTS idx_employees_dept_id ON employees (dept_id);
CREATE INDEX IF NOT EXISTS idx_employees_sector_id ON employees (sector_id);
CREATE INDEX IF NOT EXISTS idx_employees_position_id ON employees (position_id);
CREATE INDEX IF NOT EXISTS idx_employee_edit_requests_status ON employee_edit_requests (status);
CREATE INDEX IF NOT EXISTS idx_meetings_date ON meetings (meeting_date);
